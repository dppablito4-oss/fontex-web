import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { beforeEach, expect, it, vi } from "vitest";
import { LessonPage } from "./LessonPage";
import { templateScene } from "../../core/primitives/templates";
import type { PrimitiveScene } from "../../core/primitives/schema";
import type { Lesson } from "./learning-service";
const mock=vi.hoisted(()=>({load:vi.fn(),action:vi.fn(),list:vi.fn(),rpc:vi.fn()}));
vi.mock("./learning-service",()=>({loadLesson:mock.load,classroomAction:mock.action,listSubmissions:mock.list}));
vi.mock("./classroom-access",()=>({classroomClient:()=>({rpc:mock.rpc})}));
vi.mock("../../components/ProductNavigation",()=>({SiteHeader:()=>null}));
vi.mock("./ClassroomGuestProvider",()=>({ClassroomGuestBanner:()=>null}));
const source=templateScene("practice-fractions");
const lesson:Lesson={id:"c0920000-0000-4000-8000-000000000001",classroom_id:"c0920000-0000-4000-8000-000000000002",title:"Mi clase de fracciones",topic:"Fracciones",class_date:"2026-11-16",week:1,instructions:"Ajusta el denominador y responde.",due_at:null,status:null,deliveries:0,scene:source,teacher:false,attachments:[],submission:null};
beforeEach(()=>{vi.clearAllMocks();mock.load.mockResolvedValue(structuredClone(lesson));mock.action.mockResolvedValue({id:"submission"});});
it("edits only enabled values, saves a draft and submits the same canvas",async()=>{
 render(<LessonPage id={lesson.id}/>);
 await screen.findByText("Ajusta el denominador y responde.");
 fireEvent.click(screen.getByRole("button",{name:"Cambiar Denominador"}));
 fireEvent.change(screen.getByRole("textbox",{name:"Denominador"}),{target:{value:"8"}});
 fireEvent.click(screen.getByRole("button",{name:"Aplicar Denominador"}));
 expect(screen.getByText("Respuestas sin guardar")).toBeInTheDocument();
 fireEvent.click(screen.getByRole("button",{name:"Guardar borrador"}));
 await screen.findByText("Borrador guardado en el aula.");
 const saved=mock.action.mock.calls[0]![2] as {scene:PrimitiveScene};
 expect(saved.scene.id).toBe(source.id);
 expect(saved.scene.primitives.find(p=>p.kind==="geometric_shape")!.data.divisions).toBe(8);
 expect(source.primitives.find(p=>p.kind==="geometric_shape")!.data).toMatchObject({divisions:4});
 fireEvent.click(screen.getByRole("button",{name:"Entregar actividad"}));
 await screen.findByText("Actividad entregada al docente.");
 expect(mock.action).toHaveBeenLastCalledWith(lesson.id,"save",expect.objectContaining({submit:true}));
 expect(screen.queryByRole("textbox",{name:/consigna|definición/i})).not.toBeInTheDocument();
});
it("keeps unsaved answers when the server rejects or loses a save",async()=>{
 mock.action.mockRejectedValue(new Error("Tu acceso temporal venció."));render(<LessonPage id={lesson.id}/>);
 await screen.findByText("Ajusta el denominador y responde.");
 fireEvent.click(screen.getByRole("button",{name:"Cambiar Tu respuesta"}));
 fireEvent.change(screen.getByRole("textbox",{name:"Tu respuesta"}),{target:{value:"Mi respuesta guardada localmente"}});
 fireEvent.click(screen.getByRole("button",{name:"Aplicar Tu respuesta"}));
 fireEvent.click(screen.getByRole("button",{name:"Entregar actividad"}));
 await screen.findByRole("alert");
 expect(screen.getByText("Respuestas sin guardar")).toBeInTheDocument();
 expect(screen.getByRole("button",{name:"Cambiar Tu respuesta"})).toHaveTextContent("Mi respuesta guardada localmente");
});
it("gives teachers a reading view and delivery list without student submit controls",async()=>{
 mock.load.mockResolvedValue({...lesson,teacher:true});mock.list.mockResolvedValue([]);render(<LessonPage id={lesson.id}/>);
 await screen.findByText("Entregas de la clase · 0");
 await waitFor(()=>expect(mock.list).toHaveBeenCalledWith(lesson.id));
 expect(screen.queryByRole("button",{name:"Entregar actividad"})).not.toBeInTheDocument();
 expect(screen.queryByRole("button",{name:"Cambiar Denominador"})).not.toBeInTheDocument();
});
